package.path="direct/lua/?.lua;"..package.path
local m=require"model"
local function f() end
local h={switch={on=f,off=f},switchLevel={setLevel=f},windowShade={open=f,close=f,pause=f},windowShadeLevel={setShadeLevel=f},colorControl={setColor=f},colorTemperature={setColorTemperature=f}}
assert(m.command({switch=true},h,"switch","ON").command=="on")
assert(m.command({switch=true},h,"switch","toggle")==nil)
assert(m.command({switch=true,valve=true},h,"switch","ON")==nil)
assert(m.command({windowShade=true},h,"shade","CLOSE").command=="close")
assert(m.command({windowShadeLevel=true},h,"position","42").args.shadeLevel==42)
assert(m.command({windowShadeLevel=true},h,"position","101")==nil)
assert(m.command({switchLevel=true},h,"brightness","1.5")==nil)
assert(m.command({switch=true,colorControl=true},h,"hs","180,50").args.color.hue==50)
assert(m.command({switch=true,colorControl=true},h,"hs","361,10")==nil)
assert(m.numeric("energy",1000,"Wh")==1)
assert(m.numeric("current",500,"mA")==0.5)
assert(m.numeric("temperature",68,"F")==20)
assert(m.numeric("power",3,"bad")==nil)
assert(m.numeric("battery",101,"%")==nil)
assert(m.state("motion","active")=="ON")
assert(m.state("shade","partially open")=="open")
local d=m.describe("st-direct/home/zcl-plugs","abc","main","Plug","maker","model",{switch=true,powerMeter=true,energyMeter=true,voltageMeasurement=true,currentMeasurement=true},h,true,"SmartPlug")
assert(d.switch.config.payload_on=="ON" and d.power.config.unit_of_measurement=="W")
assert(d.energy.config.state_class=="total_increasing")
assert(d.current.config.device_class=="current")
local c=m.describe("st-direct/home/cover","abc","main","Window","maker","model",{windowShade=true,windowShadeLevel=true,battery=true},h,true)
assert(c.shade.config.position_topic and c.shade.commands.position and not c.switch)
local a=m.describe("st-direct/home/zcl-switch","abc","switch2","Relay","maker","model",{switch=true},h,true)
assert(a.switch.config.command_topic:find("/switch2/cmd/switch",1,true))
local b=m.describe("st-direct/home/sensor","abc","main","Button","maker","model",{button=true},h,false)
assert(not b.button)
assert(m.describe("st-direct/home/sensor","abc","main","Button","maker","model",{button=true},h,true).button)
print("direct model contract passed")
