package.path = "edge/st-local-edge/src/?.lua;" .. package.path
local w = require "wire"
local function hex(s) return (s:gsub(".", function(c) return string.format("%02x", c:byte()) end)) end
assert(hex(w.frame(0xC0, "")) == "c000")
assert(hex(w.subscribe("a","b")) == "820a00010001610100016201")
assert(hex(w.publish("a","on",true)) == "31050001616f6e")
local f = w.connect("x","u","p","a")
assert(hex(f) == "101f00044d51545404e6001400017800016100076f66666c696e65000175000170")
local packet = w.frame(0x32, w.str("a") .. w.u16(7) .. "pushed")
for i=0,#packet-1 do assert(w.pop(packet:sub(1,i)) == nil) end
local h,b,rest = w.pop(packet .. w.frame(0xD0,""))
assert(h == 0x32 and rest == string.char(0xD0,0))
local t,p,id,r = w.decode_publish(h,b)
assert(t=="a" and p=="pushed" and id==w.u16(7) and not r)
assert(hex(w.puback(id))=="40020007")
assert(w.command("a","a/on","pushed",false)=="commandOn")
assert(w.command("a","a/off","pushed",false)=="commandOff")
assert(w.command("a","a/on","pushed",true)==nil)
assert(w.command("a","a/on","off",false)==nil)
assert(w.command("a","b/on","pushed",false)==nil)
local large = string.rep("x", 300)
local hh,bb = w.pop(w.frame(0x30,large))
assert(hh==0x30 and bb==large)
assert(not pcall(w.pop,string.char(0x30,255,255,255,255)))
assert(w.private_ipv4("192.168.0.19") and w.private_ipv4("172.16.1.1"))
assert(not w.private_ipv4("8.8.8.8") and not w.private_ipv4("192.168.0.999"))
assert(w.uuid("12345678-1234-1234-1234-123456789ABC")=="12345678-1234-1234-1234-123456789abc")
assert(not w.uuid("00000000-0000-0000-0000-000000000000"))
print("MQTT codec tests passed")

assert(hex(w.subscribe("a","b","c"))=="820e0001000161010001620100016301")
assert(w.command("a","a/stop","pushed",false,true)=="commandStop")
assert(w.command("a","a/stop","pushed",false,false)==nil)
assert(w.command("a","a/stop","pushed",true,true)==nil)
assert(w.shade_state(0)=="closed" and w.shade_state(1)=="open")
assert(w.shade_state(2)=="opening" and w.shade_state(3)=="closing")
assert(w.shade_state(4)=="partially open" and w.shade_state(5)=="paused" and w.shade_state(6)=="unknown")
assert(w.shade_state(99)==nil)
